        public static BossStory Get(int speciesId){return All[Mathf.Clamp(speciesId-108,0,10)];}
        public static string Teaching(int speciesId){return Get(speciesId).instruction;}
        public static string Preparation(int speciesId){var b=Get(speciesId);return b.speaker+"："+b.preparation;}
        public static string PhaseLine(int speciesId,int phase){return Get(speciesId).phases[Mathf.Clamp(phase-1,0,2)];}
        public static string Failure(int speciesId){return Get(speciesId).failure;}
        public static string Victory(int speciesId){return Get(speciesId).aftermath;}
